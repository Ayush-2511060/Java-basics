import java.util.*;

public class loops {
    public static void main(String[] args) {
        System.out.println("------While Loop------");
        int i = 1;
        while (i <= 10) {
            System.out.print(i + " ");
            i++;
        }
        System.out.print("\n");
        System.out.println("----While loop Completed----");
        System.out.println("|=================================|");
        System.out.println("------For loop------");
        for(i = 1; i <=10; i++){
            System.out.print(i + " ");
        }
        System.out.print("\n");
        System.out.println("----For loop completed----");
    }


}
